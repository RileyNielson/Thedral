def generate_narrator_pack(book_id: str | None = None) -> str:
    conn = get_db()
    c = conn.cursor()

    if not book_id:
        c.execute("""
            SELECT id, title FROM binder_nodes 
            WHERE node_type = 'BOOK' AND (is_archived IS NULL OR is_archived = 0) 
            ORDER BY sort_order ASC LIMIT 1
        """)
        row = c.fetchone()
        if not row:
            c.execute("SELECT id, title FROM binder_nodes WHERE node_type = 'BOOK' LIMIT 1")
            row = c.fetchone()
        book_id = row["id"] if row else None

    c.execute("SELECT term, category, pronunciation, rule_definition FROM style_sheet ORDER BY category ASC, term ASC")
    style_rows = c.fetchall()

    c.execute("""
        SELECT name, role, aliases, sensory_profile, status 
        FROM canonical_entities 
        WHERE entity_type = 'CHARACTER' 
        ORDER BY role ASC, name ASC
    """)
    char_rows = c.fetchall()
    conn.close()

    output = []
    output.append("# 🎙️ AUDIOBOOK NARRATOR & PRONUNCIATION DOSSIER")
    output.append(f"**Generated:** {time.strftime('%Y-%m-%d %H:%M:%S')}")
    output.append("\n---\n")

    output.append("## 1. PHONETIC PRONUNCIATION GUIDE (Living Style Sheet)")
    if style_rows:
        output.append("| Term | Category | Phonetic Guide | Notes / Definition |")
        output.append("| :--- | :--- | :--- | :--- |")
        for r in style_rows:
            phonetic = r["pronunciation"] or "—"
            output.append(f"| **{r['term']}** | {r['category']} | `{phonetic}` | {r['rule_definition']} |")
    else:
        output.append("*No phonetic rules currently registered in style_sheet.*")

    output.append("\n---\n")
    output.append("## 2. CHARACTER VOCAL PROFILES & ACTING REGISTERS")
    if char_rows:
        for ch in char_rows:
            output.append(f"### • {ch['name']} ({ch['role']})")
            if ch["aliases"]:
                output.append(f"- **Also Known As / Addressed As:** {ch['aliases']}")
            vocal_tell = ch["sensory_profile"] or "Standard conversational register"
            output.append(f"- **Vocal Delivery & Attitude:** *{vocal_tell}*")
            output.append(f"- **Current Continuity Status:** {ch['status']}")
            output.append("")
    else:
        output.append("*No character profiles registered.*")

    output.append("\n---\n")
    output.append("*Generated by Thedral Studio. Certified for ACX / Audible production.*")
    return "\n".join(output)

def generate_authorship_certificate(book_id: str | None = None) -> dict:
    conn = get_db()
    c = conn.cursor()

    if not book_id:
        c.execute("""
            SELECT id, title, created_at FROM binder_nodes 
            WHERE node_type = 'BOOK' AND (is_archived IS NULL OR is_archived = 0) 
            ORDER BY sort_order ASC LIMIT 1
        """)
        book = c.fetchone()
        if not book:
            c.execute("SELECT id, title, created_at FROM binder_nodes WHERE node_type = 'BOOK' LIMIT 1")
            book = c.fetchone()
    else:
        c.execute("SELECT id, title, created_at FROM binder_nodes WHERE id = ?", (book_id,))
        book = c.fetchone()

    if not book:
        conn.close()
        return {
            "status": "error",
            "message": "No book found to certify.",
            "certificate_text": "No manuscript located in the database to certify."
        }

    c.execute("""
        SELECT COUNT(r.id) as total_revs, MIN(r.created_at) as earliest_rev, MAX(r.created_at) as latest_rev
        FROM node_revisions r
        JOIN binder_nodes s ON r.node_id = s.id
        JOIN binder_nodes ch ON s.parent_id = ch.id
        WHERE ch.parent_id = ?
    """, (book["id"],))
    rev_data = c.fetchone()

    c.execute("""
        SELECT COUNT(s.id) as scene_count, SUM(s.word_count) as total_words
        FROM binder_nodes s
        JOIN binder_nodes ch ON s.parent_id = ch.id
        WHERE ch.parent_id = ? AND s.node_type = 'SCENE'
    """, (book["id"],))
    stats = c.fetchone()
    c.execute("""
        SELECT s.id, s.title, s.content
        FROM binder_nodes s
        JOIN binder_nodes ch ON s.parent_id = ch.id
        WHERE ch.parent_id = ? AND s.node_type = 'SCENE'
        ORDER BY ch.sort_order ASC, s.sort_order ASC
    """, (book["id"],))
    scene_rows = c.fetchall()
    conn.close()

    total_words = stats["total_words"] or 0
    total_revs = rev_data["total_revs"] or 0
    scene_count = stats["scene_count"] or 0
    timespan_start = rev_data["earliest_rev"] or "No revision recorded"
    timespan_end = rev_data["latest_rev"] or "No revision recorded"

    snapshot = {
        "title": book["title"],
        "scenes": [
            {"id": row["id"], "title": row["title"], "prose": html_to_text(row["content"] or "")}
            for row in scene_rows
        ],
    }
    verification_hash = hashlib.sha256(
        json.dumps(snapshot, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()

    report_text = f"""DRAFTING HISTORY REPORT
======================

Manuscript: {book['title']}
Project identifier: {book['id']}
Current word count: {total_words:,} words across {scene_count} scenes
Recorded revision snapshots: {total_revs:,}
Earliest recorded revision: {timespan_start}
Latest recorded revision: {timespan_end}

CURRENT CONTENT FINGERPRINT
SHA-256: {verification_hash}

The fingerprint is calculated from the current manuscript title and the ordered
scene identifiers, titles, and plain-text prose currently stored in Thedral.
Changing any of those values changes the fingerprint. It does not include
revision history, prove when or by whom text was written, or establish human
authorship. Revision counts and dates are database records and are not an
independent audit or tamper-proof proof of provenance."""

    return {
        "status": "success",
        "report_text": report_text,
        "certificate_text": report_text,
        "verification_hash": verification_hash,
        "total_words": total_words,
        "total_revisions": total_revs,
        "drafting_start": timespan_start,
        "drafting_end": timespan_end
    }

def generate_query_synopsis(book_id: str | None = None) -> str:
    if not ENABLE_AI:
        return "Query Synopsis generation requires local AI. Running in Pure Math Mode."

    conn = get_db()
    c = conn.cursor()

    if not book_id:
        c.execute("""
            SELECT id, title FROM binder_nodes 
            WHERE node_type = 'BOOK' AND (is_archived IS NULL OR is_archived = 0) 
            ORDER BY sort_order ASC LIMIT 1
        """)
        book = c.fetchone()
        if not book:
            c.execute("SELECT id, title FROM binder_nodes WHERE node_type = 'BOOK' LIMIT 1")
            book = c.fetchone()
        book_id = book["id"] if book else None

    c.execute("""
        SELECT ch.title as ch_title, s.title as sc_title, s.synopsis, s.content
        FROM binder_nodes s
        JOIN binder_nodes ch ON s.parent_id = ch.id
        WHERE ch.parent_id = ? AND s.node_type = 'SCENE'
        ORDER BY ch.sort_order ASC, s.sort_order ASC
    """, (book_id,))
    rows = c.fetchall()
    conn.close()

    if not rows:
        return "Not enough scenes drafted to compile an industry query synopsis."

    spine_bullets = []
    for r in rows:
        plain_content = html_to_text(r["content"] or "")
        summary = r["synopsis"] or (plain_content[:140] + "..." if plain_content else "")
        if summary.strip():
            spine_bullets.append(f"- [{r['ch_title']} / {r['sc_title']}]: {summary}")

    causal_timeline = "\n".join(spine_bullets[:25])

    prompt = f"""You are a Veteran Literary Agent and Commercial Fiction Publishing Executive.
Analyze this book's causal plot spine and write a clean, compelling 1-Page Industry Query Synopsis (approx 450-500 words).

FORMAT STRICTLY INTO:
1. THE HOOK & PROTAGONIST'S DILEMMA (1 concise paragraph)
2. THE ESCALATING CONFLICT & MAJOR TURNING POINTS (2 narrative paragraphs)
3. THE CLIMAX & ULTIMATE RESOLUTION (1 paragraph - reveal the ending completely; literary agents require spoilers)

NO MARKETING FLUFF. FOCUS PURELY ON CHARACTER MOTIVE, CAUSE, AND EFFECT.

CAUSAL PLOT SPINE:
{causal_timeline}
"""

    try:
        import ollama
        resp = ollama.chat(
            model=STUDIO_MODEL, 
            messages=[{"role": "user", "content": prompt}], 
            options=LLM_OPTIONS
        )
        return resp['message']['content']
    except Exception as e:
        return f"Could not generate query synopsis: {e}"

def generate_manuscript_prose_signals(book_id: str | None = None) -> dict:
    conn = get_db()
    c = conn.cursor()

    if not book_id:
        c.execute("""
            SELECT id, title FROM binder_nodes 
            WHERE node_type = 'BOOK' AND (is_archived IS NULL OR is_archived = 0) 
            ORDER BY sort_order ASC LIMIT 1
        """)
        book = c.fetchone()
        if not book:
            c.execute("SELECT id, title FROM binder_nodes WHERE node_type = 'BOOK' LIMIT 1")
            book = c.fetchone()
        book_id = book["id"] if book else None

    if not book_id:
        conn.close()
        return {"status": "error", "message": "No manuscript found to analyze."}

    c.execute("""
        SELECT s.content 
        FROM binder_nodes s
        JOIN binder_nodes ch ON s.parent_id = ch.id
        WHERE ch.parent_id = ? AND s.node_type = 'SCENE'
        ORDER BY ch.sort_order ASC, s.sort_order ASC
    """, (book_id,))
    rows = c.fetchall()
    conn.close()

    full_text = " ".join([html_to_text(r["content"] or "") for r in rows if r["content"]])
    total_words = len(full_text.split())

    text_signals = analyze_text_signals(full_text)

    return {
        "status": "success",
        "book_id": book_id,
        "total_words": total_words,
        "text_signals": text_signals,
    }
